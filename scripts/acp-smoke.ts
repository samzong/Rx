import { spawn } from "node:child_process";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Readable, Writable } from "node:stream";
import * as acp from "@agentclientprotocol/sdk";
const root = mkdtempSync(join(tmpdir(), "rx-acp-smoke-"));
const cwd = join(root, "work");
const home = join(root, "home");
const model = process.argv[2] ?? process.env.RX_MODEL ?? "deepseek/deepseek-flash";
mkdirSync(cwd);
writeFileSync(join(cwd, "notes.txt"), "alpha\nbravo\ncharlie\n");
console.log("root", root, "model", model);
const child = spawn(process.execPath, [new URL("../src/cli.ts", import.meta.url).pathname, "acp", "-m", model], { env: { ...process.env, RX_HOME: home }, stdio: ["pipe", "pipe", "inherit"] });
const stream = acp.ndJsonStream(Writable.toWeb(child.stdin!) as WritableStream<Uint8Array>, Readable.toWeb(child.stdout!) as ReadableStream<Uint8Array>);
const kinds: string[] = [];
const client = acp.client().onNotification(acp.methods.client.session.update, ({ params }) => { kinds.push(params.update.sessionUpdate); });
await client.connectWith(stream, async (ctx) => {
  const init = await ctx.request(acp.methods.agent.initialize, { protocolVersion: acp.PROTOCOL_VERSION });
  console.log("agent", init.agentInfo?.name, init.agentInfo?.version);
  const { sessionId } = await ctx.request(acp.methods.agent.session.new, { cwd, mcpServers: [] });
  const r1 = await ctx.request(acp.methods.agent.session.prompt, { sessionId, prompt: [{ type: "text", text: "Read notes.txt and tell me its second line only." }] });
  console.log("prompt1", r1.stopReason, [...new Set(kinds)].join(","));
  kinds.length = 0;
  const p2 = ctx.request(acp.methods.agent.session.prompt, { sessionId, prompt: [{ type: "text", text: "Run the shell command `sleep 20 && echo done` and report its output." }] });
  const t = Date.now();
  while (!kinds.includes("tool_call")) await new Promise((r) => setTimeout(r, 50));
  await ctx.notify(acp.methods.agent.session.cancel, { sessionId });
  const r2 = await p2;
  console.log("prompt2", r2.stopReason, `${Date.now() - t}ms`);
  const list = await ctx.request(acp.methods.agent.session.list, { cwd });
  console.log("list", list.sessions.map((s) => s.title));
});
child.kill();
